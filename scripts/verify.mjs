import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const CONTENT = 'src/content/docs';
const LOCALES = ['en', 'es'];
const FAILURES = [];
const WARNINGS = [];

const fail = (message) => FAILURES.push(message);
const warn = (message) => WARNINGS.push(message);

/** Collect every .md/.mdx article and its frontmatter. */
function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      files.push(...walk(full));
      continue;
    }
    if (/\.mdx?$/.test(entry)) {
      files.push(full);
    }
  }
  return files;
}

/** Minimal frontmatter reader: we only need title, help.section and help.video. */
function frontmatter(file) {
  const raw = readFileSync(file, 'utf8');
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) {
    return null;
  }
  const body = match[1];
  const title = body.match(/^title:\s*(.+)$/m)?.[1]?.replace(/^['"]|['"]$/g, '');
  const section = body.match(/^\s{2}section:\s*(\S+)/m)?.[1];
  const video = body.match(/^\s{2}video:\s*(\S+)/m)?.[1];
  const hasHelp = /^help:/m.test(body);
  return { title, section, video, hasHelp, raw };
}

const articles = walk(CONTENT);
const byLocale = { en: [], es: [] };

for (const file of articles) {
  const rel = relative(CONTENT, file).split(sep).join('/');
  const isEs = rel === 'es' || rel.startsWith('es/');
  const slug = isEs ? rel.replace(/^es\/?/, '') : rel;
  const meta = frontmatter(file);

  if (!meta) {
    fail(`${rel}: missing frontmatter`);
    continue;
  }
  if (!meta.title) {
    fail(`${rel}: missing title`);
  }
  byLocale[isEs ? 'es' : 'en'].push({ rel, slug, ...meta });
}

// 1. Slug parity between languages.
const slugs = Object.fromEntries(
  LOCALES.map((locale) => [locale, new Set(byLocale[locale].map((a) => a.slug.replace(/\.mdx?$/, '')))])
);
for (const locale of LOCALES) {
  const other = locale === 'en' ? 'es' : 'en';
  for (const slug of slugs[locale]) {
    if (!slugs[other].has(slug)) {
      fail(`"${slug}" exists in ${locale} but not in ${other}`);
    }
  }
}

// 2. Same help section in both languages, and never duplicated.
const sections = { en: new Map(), es: new Map() };
for (const locale of LOCALES) {
  for (const article of byLocale[locale]) {
    if (!article.hasHelp) {
      continue;
    }
    if (!article.section) {
      fail(`${article.rel}: has a help block without a section id`);
      continue;
    }
    if (sections[locale].has(article.section)) {
      fail(`${article.rel}: duplicate help section "${article.section}"`);
    }
    sections[locale].set(article.section, article);
  }
}
for (const [section, article] of sections.en) {
  if (!sections.es.has(section)) {
    fail(`help section "${section}" (${article.rel}) has no Spanish counterpart`);
  }
}
for (const [section, article] of sections.es) {
  if (!sections.en.has(section)) {
    fail(`help section "${section}" (${article.rel}) has no English counterpart`);
  }
}

// 3. Help icons in the app: every declared appRoute must exist in the app.
//    The list is generated by `php artisan help:routes` in the Picstome repo.
const routesFile = 'scripts/app-routes.json';
if (existsSync(routesFile)) {
  const known = new Set(JSON.parse(readFileSync(routesFile, 'utf8')));
  for (const locale of LOCALES) {
    for (const article of byLocale[locale]) {
      const routes = [...article.raw.matchAll(/^\s{2}appRoutes:\s*\[(.*)\]$/gm)].flatMap((match) =>
        match[1]
          .split(',')
          .map((route) => route.trim().replace(/^['"]|['"]$/g, ''))
          .filter(Boolean)
      );
      for (const route of routes) {
        if (!known.has(route)) {
          fail(`${article.rel}: appRoutes references unknown route "${route}"`);
        }
      }
    }
  }
}

// 4. Video assets: every declared slug must have a webm and a poster.
for (const locale of LOCALES) {
  for (const article of byLocale[locale]) {
    if (!article.video) {
      continue;
    }
    for (const extension of ['webm', 'webp']) {
      if (!existsSync(join('public/videos', `${article.video}.${extension}`))) {
        fail(`${article.rel}: missing public/videos/${article.video}.${extension}`);
      }
    }
  }
}

// 5. Built output: both locales rendered and the help snapshot exists.
if (existsSync(DIST)) {
  for (const locale of LOCALES) {
    for (const slug of slugs[locale]) {
      // A section index (`culling/index.mdx`) builds to `culling/index.html`,
      // while the root `index.mdx` builds to `index.html`.
      const path =
        slug === 'index'
          ? join(DIST, locale === 'en' ? '' : 'es', 'index.html')
          : join(DIST, locale === 'en' ? '' : 'es', slug.replace(/\/index$/, ''), 'index.html');
      if (!existsSync(path)) {
        fail(`missing built page: ${path}`);
      }
    }
    const snapshot = join(DIST, 'api', `help-${locale}.json`);
    if (!existsSync(snapshot)) {
      fail(`missing help snapshot: ${snapshot}`);
    } else {
      const data = JSON.parse(readFileSync(snapshot, 'utf8'));
      const count = Object.keys(data).filter((key) => !key.startsWith('page:')).length;
      if (count === 0) {
        fail(`${snapshot} exports no sections`);
      }
      for (const [key, entry] of Object.entries(data)) {
        if (key.startsWith('page:')) {
          continue;
        }
        if (!entry.html || entry.html.length < 200) {
          fail(`${snapshot}: section "${key}" has suspiciously little HTML`);
        }
        if (/href="\/(?!\/)/.test(entry.html)) {
          fail(`${snapshot}: section "${key}" still has relative links`);
        }
      }
    }
  }
}

// 6. Images must carry alt text in the Markdown sources.
for (const article of articles) {
  const raw = readFileSync(article, 'utf8');
  for (const match of raw.matchAll(/!\[([^\]]*)\]\(([^)]+)\)/g)) {
    if (!match[1].trim()) {
      warn(`${relative(CONTENT, article)}: image ${match[2]} has no alt text`);
    }
  }
}

const report = (label, list) => {
  if (list.length === 0) {
    return;
  }
  console.error(`\n${label} (${list.length})`);
  for (const item of list) {
    console.error(`  - ${item}`);
  }
};

report('Errors', FAILURES);
report('Warnings', WARNINGS);

if (FAILURES.length > 0) {
  console.error('\nDocs verification failed.\n');
  process.exit(1);
}

console.log(
  `Docs verification passed: ${articles.length} articles, ${sections.en.size} help sections, ${LOCALES.length} locales.`
);
